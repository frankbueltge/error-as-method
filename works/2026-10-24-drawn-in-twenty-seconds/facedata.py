#!/usr/bin/env python3
"""Write face-data.js for index.html: per thing, 240 people from the pool (seed 156), the six shown,
the three arms' drawings in maker order, the people's null and D per arm from results.json, and
which H drawings counted as traced."""
import json, os, random
HERE = os.path.dirname(os.path.abspath(__file__))
plan = json.load(open(os.path.join(HERE, "plan.json")))
dr = json.load(open(os.path.join(HERE, "drawings.json")))
res = json.load(open(os.path.join(HERE, "results.json")))
rng = random.Random(156)
things = []
for c in plan["categories"]:
    name = c["category"]
    P = json.load(open(os.path.join(HERE, "pools", name.replace(" ", "_") + ".json")))
    r = res["things"][name]
    things.append({
        "name": name, "npool": len(P["pool"]),
        "people": [x["drawing"] for x in rng.sample(P["pool"], 240)],
        "shown": [x["drawing"] for x in P["shown"]],
        "arms": {a: [dr.get(f"{a}{n}", {}).get(name) for n in range(1, 7)] for a in "SFH"},
        "null": r["people_null"], "D": r["D"],
        "traced": [r["H_cells"].get(f"H{n}", {}).get("traced", False) for n in range(1, 7)],
    })
open(os.path.join(HERE, "face-data.js"), "w").write(
    "// generated by facedata.py; people's drawings: Quick, Draw! dataset, CC BY 4.0\nwindow.FACE=" +
    json.dumps({"things": things}, separators=(",", ":")) + ";\n")
print("face-data.js", os.path.getsize(os.path.join(HERE, "face-data.js")))
