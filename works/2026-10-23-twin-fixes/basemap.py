"""Turn Natural Earth 1:110m land (public domain), as packaged in world-atlas@2.0.2 land-110m.json (ISC),
into one SVG path in an equirectangular frame of 360 x 180 units (x = lon + 180, y = 90 - lat).
Usage: python3 basemap.py <land-110m.json>  -> writes land.js (window.LAND = "<path d>")."""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
t = json.load(open(sys.argv[1], encoding="utf8"))
sx, sy = t["transform"]["scale"]; tx, ty = t["transform"]["translate"]
arcs = []
for arc in t["arcs"]:
    x = y = 0; pts = []
    for dx, dy in arc:
        x += dx; y += dy
        pts.append((x * sx + tx, y * sy + ty))
    arcs.append(pts)
def ring(idx):
    pts = []
    for i in idx:
        a = arcs[i] if i >= 0 else arcs[~i][::-1]
        pts += a if not pts else a[1:]
    return pts
d = []
for g in t["objects"]["land"]["geometries"]:
    polys = g["arcs"] if g["type"] == "MultiPolygon" else [g["arcs"]]
    for poly in polys:
        for r in poly:
            pts = ring(r)
            d.append("M" + "L".join("%.2f %.2f" % (lon + 180, 90 - lat) for lon, lat in pts) + "Z")
open(os.path.join(HERE, "land.js"), "w").write("// Natural Earth 1:110m land, public domain, via world-atlas 2.0.2 (ISC). Generated by basemap.py.\nwindow.LAND = \"%s\";\n" % "".join(d))
print(len("".join(d)))
