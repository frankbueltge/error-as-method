"""Write face-data.js for index.html from plan.json, results.json and posthoc.json.

usage: python3 facedata.py
"""
import json

plan = json.load(open("plan.json"))
r = json.load(open("results.json"))
cells = r["cells"]
out = {"summary": r["summary"], "S": [], "N": [], "P": []}
for k in plan["keys"]["S"]:
    c = cells[k["id"]]
    out["S"].append({"cue": k["cue"], "G": k["G"], "people": k["people"], "makers": c["norm"], "raw": c["raw"],
                     "unanimous": c["unanimous"], "modal": c["modal"],
                     "modal_raw": c["raw"][c["norm"].index(c["modal"])],
                     "p3": k["p_three_agree"]})
for k in plan["keys"]["N"]:
    c = cells[k["id"]]
    out["N"].append({"cue": k["cue"], "excluded": k["excluded"], "makers": c["norm"], "raw": c["raw"],
                     "unanimous": c["unanimous"], "modal": c["modal"]})
for k in plan["keys"]["P"]:
    c = cells[k["id"]]
    out["P"].append({"a": k["a"], "b": k["b"], "kind": k["kind"], "shared": k["shared"],
                     "makers": c["norm"], "raw": c["raw"], "unanimous": c["unanimous"], "modal": c["modal"]})
with open("face-data.js", "w") as fh:
    fh.write("// Generated by facedata.py. People's counts: USF Free Association Norms, Appendix A\n"
             "// (Nelson, McEvoy & Schreiber 1998), the 24 cues used only.\n")
    fh.write("window.BLANK = " + json.dumps(out, separators=(",", ":")) + ";\n")
print("ok")
